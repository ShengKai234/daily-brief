-- ---------- backend roles, grants and policies (docs/auth-passkey-design.md 4.4) ----------
-- brief_migrator owns the tables and runs migrations. brief_runtime (Lambda, scheduler) and
-- brief_admin (auth_admin CLI) are LOGIN roles created by Kai (Supabase) or by the local db
-- init script, with passwords outside the repo. Neither owns tables or has BYPASSRLS.
-- Client roles get nothing: revoke from PUBLIC always, from anon/authenticated where they exist.

do $$
declare r text;
begin
  foreach r in array array['anon', 'authenticated'] loop
    if exists (select 1 from pg_roles where rolname = r) then
      execute format('revoke all on all tables in schema public from %I', r);
      execute format('revoke all on all sequences in schema public from %I', r);
      execute format('alter default privileges in schema public revoke all on tables from %I', r);
      execute format('alter default privileges in schema public revoke all on sequences from %I', r);
    end if;
  end loop;
end $$;
revoke all on all tables in schema public from public;
revoke all on all sequences in schema public from public;
alter default privileges in schema public revoke all on tables from public;
alter default privileges in schema public revoke all on sequences from public;

-- Default privileges of the migration role, both global and per schema: a global default grant
-- would otherwise reach future tables (TRUNCATE ignores RLS). Run as brief_migrator or a member.
do $$
declare r text;
begin
  if exists (select 1 from pg_roles where rolname = 'brief_migrator') then
    foreach r in array array['public', 'anon', 'authenticated'] loop
      if r = 'public' or exists (select 1 from pg_roles where rolname = r) then
        execute format('alter default privileges for role brief_migrator revoke all on tables from %s', r);
        execute format('alter default privileges for role brief_migrator revoke all on sequences from %s', r);
        execute format('alter default privileges for role brief_migrator revoke all on functions from %s', r);
        execute format('alter default privileges for role brief_migrator in schema public revoke all on tables from %s', r);
        execute format('alter default privileges for role brief_migrator in schema public revoke all on sequences from %s', r);
      end if;
    end loop;
  end if;
end $$;

grant usage on schema public to brief_runtime, brief_admin;

-- brief_runtime: read and write everything it serves, but cannot create enrollment tokens.
grant select, insert, update, delete on
  profiles, agent_settings, topics, subscriptions, delivery_slots, jobs, reports,
  report_sections, report_items, item_marks, usage_logs,
  passkey_credentials, auth_sessions, webauthn_ceremonies, auth_rate_limits, auth_events
  to brief_runtime;
grant select, update, delete on enrollment_tokens to brief_runtime;

do $$
declare t text;
begin
  foreach t in array array['profiles', 'agent_settings', 'topics', 'subscriptions', 'delivery_slots',
                           'jobs', 'reports', 'report_sections', 'report_items', 'item_marks', 'usage_logs',
                           'passkey_credentials', 'auth_sessions', 'webauthn_ceremonies',
                           'auth_rate_limits', 'auth_events'] loop
    execute format('create policy runtime_all on %I for all to brief_runtime using (true) with check (true)', t);
  end loop;
end $$;
create policy runtime_select on enrollment_tokens for select to brief_runtime using (true);
create policy runtime_update on enrollment_tokens for update to brief_runtime using (true) with check (true);
create policy runtime_cleanup on enrollment_tokens for delete to brief_runtime
  using (coalesce(used_at, revoked_at, expires_at) < now() - interval '90 days');

-- brief_admin: issue and revoke tokens, bootstrap the owner, disable/enable users, revoke sessions.
-- It cannot create sessions. `auth_admin dev-session` (APP_ENV=local only) uses the local runtime
-- connection (DATABASE_URL as brief_runtime), never the admin connection.
grant select, insert, update on enrollment_tokens, profiles to brief_admin;
grant select, insert on agent_settings, auth_events to brief_admin;
grant select, update on auth_sessions, webauthn_ceremonies to brief_admin;
grant select on passkey_credentials, topics, subscriptions, delivery_slots, jobs, reports,
  report_sections, report_items, item_marks, usage_logs to brief_admin;

create policy admin_tokens   on enrollment_tokens   for all    to brief_admin using (true) with check (true);
create policy admin_profiles on profiles            for all    to brief_admin using (true) with check (true);
create policy admin_sessions on auth_sessions       for all    to brief_admin using (true) with check (true);
create policy admin_ceremony on webauthn_ceremonies for all    to brief_admin using (true) with check (true);
create policy admin_settings on agent_settings      for all    to brief_admin using (true) with check (true);
