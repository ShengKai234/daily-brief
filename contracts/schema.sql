do $$
declare t text;
begin
  foreach t in array array['passkey_credentials', 'topics', 'subscriptions', 'delivery_slots', 'jobs',
                           'reports', 'report_sections', 'report_items', 'item_marks', 'usage_logs'] loop
    execute format('create policy admin_read on %I for select to brief_admin using (true)', t);
  end loop;
end $$;
-- Policies grant nothing by themselves: table privileges above are the second gate, so a
-- "for all" policy on a table where brief_admin has only select still allows only select.
